import { readFileSync } from "node:fs";

const geo = JSON.parse(readFileSync(process.argv[2], "utf8"));
const rings = [];
for (const f of geo.features) {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  for (const poly of polys) {
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    for (const [x, y] of poly[0]) {
      x0 = Math.min(x0, x); x1 = Math.max(x1, x);
      y0 = Math.min(y0, y); y1 = Math.max(y1, y);
    }
    rings.push({ poly, box: [x0, x1, y0, y1] });
  }
}
const inside = (ring, x, y) => {
  let c = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const land = (lon, lat) =>
  rings.some(({ poly, box }) => lon >= box[0] && lon <= box[1] && lat >= box[2] && lat <= box[3] &&
    inside(poly[0], lon, lat) && !poly.slice(1).some((h) => inside(h, lon, lat)));

const rows = [];
let cells = 0;
for (let r = 0; r < 180; r++) {
  const lat = 89.5 - r;
  const runs = [];
  let cur = false, n = 0;
  for (let c = 0; c < 360; c++) {
    const v = land(-179.5 + c, lat);
    if (v) cells++;
    if (v === cur) n++;
    else { runs.push(n); cur = v; n = 1; }
  }
  runs.push(n);
  rows.push(runs.map((k) => k.toString(36)).join("."));
}
process.stdout.write(`// Land mask of the Earth at 1 degree, from Natural Earth 1:110m land (public domain,
// naturalearthdata.com); generated by tools/make-land.mjs (${cells} of 64800 cells are land).
// Rows run from 90N to 90S and columns from 180W to 180E. Each row lists run lengths, in
// base 36, alternating sea, land, sea, ...
const RLE = "${rows.join(",")}";

// isLand(lat, lon) in degrees.
const mask = new Uint8Array(360 * 180);
RLE.split(",").forEach((row, r) => {
  let c = 0, land = 0;
  for (const run of row.split(".")) {
    const n = parseInt(run, 36);
    if (land) mask.fill(1, r * 360 + c, r * 360 + c + n);
    c += n;
    land ^= 1;
  }
});
export function isLand(lat, lon) {
  const r = Math.min(179, Math.max(0, Math.floor(90 - lat)));
  const c = (((Math.floor(lon + 180) % 360) + 360) % 360);
  return mask[r * 360 + c] === 1;
}
`);
